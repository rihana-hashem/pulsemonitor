using Microsoft.EntityFrameworkCore;
using PulseMonitor.Application.Servers;
using PulseMonitor.Domain.Exceptions;
using PulseMonitor.Infrastructure.Persistence;
using PulseMonitor.Infrastructure.Persistence.Models;

namespace PulseMonitor.Infrastructure.Services;

public sealed class ServerCommandService(
    PulseMonitorDbContext dbContext,
    TimeProvider timeProvider) : IServerCommandService
{
    public async Task<ServerDto> CreateAsync(
        CreateServerCommand command,
        CancellationToken cancellationToken = default)
    {
        var serverName = command.ServerName.Trim();

        await EnsureNameIsAvailableAsync(serverName, null, cancellationToken);

        var server = new Server
        {
            ServerName = serverName,
            IpAddress = command.IpAddress.Trim(),
            Description = command.Description,
            IsActive = true
        };

        dbContext.Servers.Add(server);
        await SaveChangesAsync(serverName, cancellationToken);

        // CreatedAt is generated by the database and read back on insert.
        return ToDto(server);
    }

    public async Task<ServerDto> UpdateAsync(
        UpdateServerCommand command,
        CancellationToken cancellationToken = default)
    {
        var server = await FindServerAsync(command.ServerId, cancellationToken);
        var serverName = command.ServerName.Trim();

        await EnsureNameIsAvailableAsync(serverName, server.ServerId, cancellationToken);

        server.ServerName = serverName;
        server.IpAddress = command.IpAddress.Trim();
        server.Description = command.Description;
        server.IsActive = command.IsActive;

        await SaveChangesAsync(serverName, cancellationToken);

        return ToDto(server);
    }

    public async Task DeleteAsync(
        int serverId,
        CancellationToken cancellationToken = default)
    {
        var server = await FindServerAsync(serverId, cancellationToken);
        var now = timeProvider.GetUtcNow().UtcDateTime;

        server.DeletedAt = now;
        server.IsActive = false;

        // A deleted server is never evaluated again, so its open alerts would stay
        // "Triggered" forever. Close them as part of the same save.
        var activeAlerts = await dbContext.Alerts
            .Where(a => a.ServerId == serverId && a.Status == "Triggered")
            .ToListAsync(cancellationToken);

        foreach (var alert in activeAlerts)
        {
            alert.Status = "Resolved";
            alert.ResolvedAt = now;
        }

        await dbContext.SaveChangesAsync(cancellationToken);
    }

    private async Task<Server> FindServerAsync(
        int serverId,
        CancellationToken cancellationToken)
    {
        return await dbContext.Servers
            .SingleOrDefaultAsync(s => s.ServerId == serverId, cancellationToken)
            ?? throw new NotFoundException("Server", serverId);
    }

    private async Task EnsureNameIsAvailableAsync(
        string serverName,
        int? excludedServerId,
        CancellationToken cancellationToken)
    {
        var nameTaken = await dbContext.Servers
            .AnyAsync(
                s => s.ServerName == serverName && s.ServerId != excludedServerId,
                cancellationToken);

        if (nameTaken)
            throw DuplicateName(serverName);
    }

    private async Task SaveChangesAsync(
        string serverName,
        CancellationToken cancellationToken)
    {
        try
        {
            await dbContext.SaveChangesAsync(cancellationToken);
        }
        // Another request took the name between our check and this save.
        catch (DbUpdateException ex) when (SqlServerErrors.IsUniqueViolation(ex))
        {
            throw DuplicateName(serverName);
        }
    }

    private static ConflictException DuplicateName(string serverName) =>
        new($"A server named '{serverName}' already exists.");

    private static ServerDto ToDto(Server server) =>
        new(
            server.ServerId,
            server.ServerName,
            server.IpAddress,
            server.Description,
            server.IsActive,
            server.CreatedAt);

}
